import { describe, it, expect, beforeEach, afterEach, afterAll, vi } from "vitest";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// Email agents must know the identity (address) of the mailbox they operate
// on (#1095). Up to OpenClaw 2026.7 Pinchy wrote that context into TOOLS.md;
// OpenClaw 2026.9 stopped loading TOOLS.md as bootstrap context (only its
// doctor merges it into AGENTS.md, and nothing in a Pinchy deployment runs
// doctor). AGENTS.md is the user's file, so the mailbox context moves into
// IDENTITY.md — generated by Pinchy, never writable by the agent, and loaded
// by OpenClaw for every main, channel and cron session.
//
// Two writers now share IDENTITY.md: the agent's name/tagline (create and
// PATCH) and the mailbox section (every config regeneration). Each owns its
// half and must leave the other's intact, whichever runs last.
//
// Real filesystem: the property under test is what ends up in the file after
// a sequence of writes, which a mocked fs would only model.
const TEST_ROOT = mkdtempSync(join(tmpdir(), "workspace-mailbox-"));
process.env.WORKSPACE_BASE_PATH = TEST_ROOT;

let workspace: typeof import("@/lib/workspace");
const AGENT_ID = "agent-mailbox-1";
const identityPath = () => join(TEST_ROOT, AGENT_ID, "IDENTITY.md");
const toolsPath = () => join(TEST_ROOT, AGENT_ID, "TOOLS.md");
const readIdentity = () => readFileSync(identityPath(), "utf-8");

const HERMES = { address: "hermes@example.com", label: "Work Gmail", operations: ["read"] };
const IRIS = { address: "iris@example.com", label: "iris@example.com", operations: ["send"] };

beforeEach(async () => {
  vi.resetModules();
  workspace = await import("@/lib/workspace");
  mkdirSync(join(TEST_ROOT, AGENT_ID), { recursive: true });
});

afterEach(() => {
  rmSync(join(TEST_ROOT, AGENT_ID), { recursive: true, force: true });
});

afterAll(() => {
  rmSync(TEST_ROOT, { recursive: true, force: true });
});

describe("generateMailboxContent", () => {
  it("returns empty content for an empty mailbox list (no stale section)", () => {
    expect(workspace.generateMailboxContent([])).toBe("");
  });

  it("renders a connected-email section for a single mailbox", () => {
    const content = workspace.generateMailboxContent([
      {
        address: "hermes@example.com",
        label: "Work Gmail",
        operations: ["read", "search"],
      },
    ]);

    // Heading-level section for connected email.
    expect(content).toContain("## Connected Email");
    // The mailbox address is the headline of its block.
    expect(content).toContain("### hermes@example.com");
    // The Pinchy connection label is shown because it differs from the address.
    expect(content).toContain("Pinchy connection label: Work Gmail");
    // Operations are rendered human-readable, in canonical order.
    expect(content).toContain("Granted operations: read and search messages, search the mailbox");
  });

  it("states that the mailbox identity is not necessarily the chatting user's address", () => {
    const content = workspace.generateMailboxContent([
      { address: "shared@example.com", label: "shared@example.com", operations: ["read"] },
    ]);
    // Shared agents serve multiple users — the mailbox identity must not be
    // conflated with the identity of whoever is currently chatting.
    expect(content).toContain("not necessarily the personal address of the user");
  });

  it("omits the label line when the label equals the address (name defaults to address)", () => {
    const content = workspace.generateMailboxContent([
      { address: "same@example.com", label: "same@example.com", operations: ["read"] },
    ]);
    expect(content).toContain("### same@example.com");
    expect(content).not.toContain("Pinchy connection label");
  });

  it("renders every entry when given multiple mailboxes (no single-entry assumption)", () => {
    const content = workspace.generateMailboxContent([
      { address: "first@example.com", label: "First", operations: ["read"] },
      { address: "second@example.com", label: "second@example.com", operations: ["send"] },
      { address: "third@example.com", label: "Third Mailbox", operations: ["draft", "send"] },
    ]);

    expect(content).toContain("### first@example.com");
    expect(content).toContain("Pinchy connection label: First");
    expect(content).toContain("### second@example.com");
    expect(content).toContain("### third@example.com");
    expect(content).toContain("Granted operations: create drafts, send email");
    // Exactly one section heading — entries are blocks inside it.
    expect(content.match(/## Connected Email/g)).toHaveLength(1);
  });

  it("renders the legacy 'list' operation with a human-readable label", () => {
    // "list" is a legacy alias (pre-#328 template creation) that grants the
    // same toolset as "read"/"search" — see EMAIL_OPERATION_DISPLAY_ORDER in
    // tool-registry.ts. The mailbox section must render it with a label, not the raw
    // string, so a legacy list-row agent's bootstrap file stays readable.
    const content = workspace.generateMailboxContent([
      { address: "legacy@example.com", label: "legacy@example.com", operations: ["list"] },
    ]);
    expect(content).toContain("Granted operations: list messages");
  });

  it("renders unknown operations literally (no prototype-key lookup)", () => {
    // A label lookup via OBJ[op] would resolve "constructor" to a function on
    // Object.prototype and render its source. The Map-based lookup must fall
    // back to the raw operation string for anything it does not know.
    const content = workspace.generateMailboxContent([
      { address: "edge@example.com", label: "edge@example.com", operations: ["constructor"] },
    ]);
    expect(content).toContain("Granted operations: constructor");
    expect(content).not.toContain("function");
  });

  it("renders 'none' when a mailbox has no granted operations", () => {
    const content = workspace.generateMailboxContent([
      { address: "idle@example.com", label: "idle@example.com", operations: [] },
    ]);
    expect(content).toContain("Granted operations: none");
  });
});

describe("writeMailboxContext", () => {
  it("adds the mailbox section to IDENTITY.md below the agent's identity", () => {
    workspace.writeIdentityFile(AGENT_ID, { name: "Hermes", tagline: "Handles the inbox" });

    workspace.writeMailboxContext(AGENT_ID, [HERMES]);

    const identity = readIdentity();
    expect(identity.startsWith("# Hermes\n> Handles the inbox\n")).toBe(true);
    expect(identity).toContain("## Connected Email");
    expect(identity).toContain("### hermes@example.com");
    expect(identity).toContain("- Pinchy connection label: Work Gmail");
  });

  it("replaces the previous mailbox section instead of appending another one", () => {
    workspace.writeIdentityFile(AGENT_ID, { name: "Hermes", tagline: null });
    workspace.writeMailboxContext(AGENT_ID, [HERMES]);

    workspace.writeMailboxContext(AGENT_ID, [IRIS]);

    const identity = readIdentity();
    expect(identity.match(/^## Connected Email$/gm)).toHaveLength(1);
    expect(identity).toContain("### iris@example.com");
    expect(identity).not.toContain("hermes@example.com");
  });

  it("removes the section when the agent has no mailbox, keeping the identity", () => {
    workspace.writeIdentityFile(AGENT_ID, { name: "Hermes", tagline: "Handles the inbox" });
    workspace.writeMailboxContext(AGENT_ID, [HERMES]);

    workspace.writeMailboxContext(AGENT_ID, []);

    expect(readIdentity()).toBe(
      workspace.generateIdentityContent({ name: "Hermes", tagline: "Handles the inbox" })
    );
  });

  it("does not create IDENTITY.md just to say there is no mailbox", () => {
    workspace.writeMailboxContext(AGENT_ID, []);
    expect(existsSync(identityPath())).toBe(false);
  });

  it("creates the workspace when it does not exist yet", () => {
    rmSync(join(TEST_ROOT, AGENT_ID), { recursive: true, force: true });

    workspace.writeMailboxContext(AGENT_ID, [HERMES]);

    expect(readIdentity()).toContain("### hermes@example.com");
  });

  it("removes the TOOLS.md an earlier Pinchy wrote", () => {
    // OpenClaw 2026.9 no longer loads it, so it can only go stale — and
    // `openclaw doctor --fix` would merge a stale mailbox identity into the
    // user's AGENTS.md, where nothing ever removes it again.
    writeFileSync(toolsPath(), "## Connected Email\n\n### old@example.com\n");

    workspace.writeMailboxContext(AGENT_ID, [HERMES]);
    expect(existsSync(toolsPath())).toBe(false);

    writeFileSync(toolsPath(), "## Connected Email\n\n### old@example.com\n");
    workspace.writeMailboxContext(AGENT_ID, []);
    expect(existsSync(toolsPath())).toBe(false);
  });

  it("rejects path-traversal agent ids", () => {
    expect(() => workspace.writeMailboxContext("../evil", [])).toThrow("Invalid agentId: ../evil");
  });
});

describe("writeIdentityFile with a mailbox section present", () => {
  it("keeps the mailbox section when the agent is renamed", () => {
    workspace.writeIdentityFile(AGENT_ID, { name: "Hermes", tagline: null });
    workspace.writeMailboxContext(AGENT_ID, [HERMES]);

    workspace.writeIdentityFile(AGENT_ID, { name: "Hermes II", tagline: "Now with drafts" });

    const identity = readIdentity();
    expect(identity.startsWith("# Hermes II\n> Now with drafts\n")).toBe(true);
    expect(identity).not.toContain("# Hermes\n");
    expect(identity.match(/^## Connected Email$/gm)).toHaveLength(1);
    expect(identity).toContain("### hermes@example.com");
  });

  it("is byte-identical to before for an agent without a mailbox", () => {
    workspace.writeIdentityFile(AGENT_ID, { name: "Plain", tagline: null });
    expect(readIdentity()).toBe("# Plain");
  });
});
